//! The application's build script.
//!
//! # What it does
//!
//! **The dependency list is the plugin list.**
//!
//! A plugin crate has to be a dependency of the application — that is what
//! "linked in" means — but the application should not have to *name* it.
//! Rust will drop a dependency that nothing refers to, and a dropped
//! dependency takes its registrations with it, so something has to refer to
//! it.
//!
//! This script reads the application's own manifest, finds the dependencies
//! that are plugins, and writes the references:
//!
//! ```text
//! use craftkit_plugin_hello as _;
//! ```
//!
//! So the wiring is **generated from the manifest**, and the manifest is the
//! only place a plugin is written down. Adding a plugin is one line in
//! `Cargo.toml` and nothing anywhere else.
//!
//! # Why a plugin is a dependency and not a path found at run time
//!
//! A plugin could also be a `.so` loaded with `dlopen` while the program
//! runs. That is a different door with different properties — it needs a
//! shared build of the SDK, or an explicit hand-off of the registry — and it
//! is worth having. What this script does is the other door: the plugin is
//! part of the program, so the compiler checks it, the linker keeps it, and
//! its commands are there from the first instruction.

use std::path::Path;

/// The prefix a dependency's name has to have to be a plugin.
const PLUGIN_PREFIX: &str = "craftkit-plugin-";

fn main() {
    let manifest = std::env::var("CARGO_MANIFEST_DIR").unwrap_or_default();
    let manifest = std::path::Path::new(&manifest).join("Cargo.toml");
    println!("cargo:rerun-if-changed={}", manifest.display());

    let plugins = plugin_dependencies(&manifest);
    println!("cargo:rerun-if-changed=build.rs");

    let mut generated = String::new();
    generated.push_str("// Generated by the build script. Do not edit.\n");
    generated.push_str("//\n");
    generated.push_str("// The plugins are the dependencies whose names begin with ");
    generated.push_str(PLUGIN_PREFIX);
    generated.push_str(".\n\n");
    for plugin in &plugins {
        // The reference that keeps the crate in the binary. Without it the
        // linker drops the crate, and the crate's registrations go with it.
        generated.push_str("use ");
        generated.push_str(&plugin.replace('-', "_"));
        generated.push_str(" as _;\n");
    }

    let out = std::path::Path::new(&std::env::var("OUT_DIR").unwrap_or_default()).join("plugins.rs");
    if std::fs::write(&out, generated).is_err() {
        panic!("could not write {}", out.display());
    }
}

/// The plugin dependencies of a manifest.
///
/// A manifest is not a table this program can trust: it is a file a person
/// wrote. So this reads it as **text**, and looks for the lines that name a
/// plugin — the same way the gates of the tree this replaces read a file as
/// text and ask what is in it.
fn plugin_dependencies(manifest: &Path) -> Vec<String> {
    let Ok(text) = std::fs::read_to_string(manifest) else { return Vec::new() };
    let mut plugins: Vec<String> = Vec::new();
    let mut in_dependencies = false;
    for line in text.lines() {
        let line = line.trim();
        if line.starts_with('[') {
            in_dependencies = line == "[dependencies]";
            continue;
        }
        if !in_dependencies || line.starts_with('#') {
            continue;
        }
        let Some((name, _)) = line.split_once('=') else { continue };
        let name = name.trim().trim_matches('"');
        if name.starts_with(PLUGIN_PREFIX) && !plugins.contains(&name.to_string()) {
            plugins.push(name.to_string());
        }
    }
    plugins
}
