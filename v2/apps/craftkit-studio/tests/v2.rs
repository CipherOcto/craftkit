fn a_plugin_can_add_a_kind_a_tool_and_a_layer() {
    let ecosystem = ecosystem();
    assert!(ecosystem.kinds.get("geometry.rect").is_some());
    assert!(ecosystem.tools.get("tool.rect").is_some());
    assert!(ecosystem.layers.get("geometry").is_some());
    assert!(ecosystem.panels.get("panel.shapes").is_some());
}

/// The application names no plugin.
///
/// The wiring is generated by the build script from the dependency list, so
/// the source of the application does not mention a plugin. If somebody
/// adds a `use` of a plugin here, this test says so.
#[test]
fn the_application_names_no_plugin() {
    let source = std::fs::read_to_string(concat!(env!("CARGO_MANIFEST_DIR"), "/src/lib.rs"))
        .expect("the application's source is readable");
    assert!(
        !source.contains("craftkit_plugin"),
        "the application names a plugin: the wiring is meant to be generated"
    );
}

/// Every plugin is anchored.
///
/// The anchor is the one name the application gives a plugin crate, and it
/// is what keeps the plugin's items in the program on a target whose linker
/// drops a crate that nothing names — `wasm32-unknown-unknown`, where the
