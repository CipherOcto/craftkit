//! `craftkit-studio` — an application.
//!
//! # What it shows
//!
//! Five things, in the order they happen:
//!
//! 1. **The ecosystem is built from what was linked in.** There is no list
//!    here. Every contribution the linker put there is collected, and the
//!    checks that only make sense across them — a tool that runs a command
//!    that is not there, a contribution in a layer that is not there — are
//!    made **before** anybody draws anything.
//! 2. **A plugin's commands are in it.** `craftkit-plugin-hello` and
//!    `craftkit-plugin-shapes` are dependencies of this crate, and this
//!    crate names no symbol of either: the build script writes the
//!    references from the dependency list.
//! 3. **A plugin can add document semantics.** The shapes plugin adds a
//!    **kind of node**, and the core draws it by asking the kind.
//! 4. **A command can be made while the program runs.** The registry is a
//!    value, and a command can be added to it at any moment.
//! 5. **One way to run a command.** Everything above — the toolbar, an
//!    agent, a script, a test — calls [`Session::execute`] and nothing else.

#![deny(
    clippy::unwrap_used,
    clippy::expect_used,
    clippy::panic,
    clippy::unimplemented,
    clippy::todo,
    clippy::unreachable
)]
#![forbid(unsafe_code)]

pub mod commands;

// The plugins. Generated by the build script from the dependency list, so
// this crate names no plugin and does not have to change when one is added.
include!(concat!(env!("OUT_DIR"), "/plugins.rs"));

use craftkit_sdk::Ecosystem;

/// The ecosystem of this application.
///
/// Every contribution that was linked in: the application's own, and every
/// plugin's.
///
/// The ecosystem is **refused**, not repaired: a missing command or a
/// missing layer is a refusal, and the caller is told what was refused.
pub fn ecosystem() -> Result<Ecosystem, craftkit_sdk::EcosystemError> {
    Ecosystem::from_inventory()
}

/// Start a plugin and put its commands in the ecosystem.
///
/// The **third door**: the plugin is a program, it is not linked in, and
/// its commands arrive over a wire. They land in the same registry as the
/// linked ones, so nothing else in the program has to know they came from
/// somewhere else.
///
/// The plugin is **kept alive** in the ecosystem's own store, so that the
/// program that is running stays running for as long as the commands are
/// there.
pub fn load_plugin(
    ecosystem: &mut Ecosystem,
    program: &str,
    args: &[&str],
) -> Result<(), craftkit_sdk::PluginError> {
    let mut plugin = craftkit_sdk::LoadedPlugin::spawn(program, args)?;
    plugin.register(&mut ecosystem.commands)?;
    // The plugin is a **program**, and a program that is not wanted any
    // more should not be left running. The loaded plugins are kept here so
    // that they stay alive for as long as their commands are in the
    // registry, and so that they are all stopped when this ends.
    loaded()
        .lock()
        .map_err(|_| craftkit_sdk::PluginError::Protocol("the loaded plugins are poisoned".to_string()))?
        .push(plugin);
    Ok(())
}

/// The plugins that were loaded while the program ran.
///
/// A plugin is a process, so somebody has to hold it: dropping it would
/// stop the program, and the commands would be left in the registry with
/// nothing behind them.
fn loaded() -> &'static std::sync::Mutex<Vec<craftkit_sdk::LoadedPlugin>> {
    static LOADED: std::sync::Mutex<Vec<craftkit_sdk::LoadedPlugin>> = std::sync::Mutex::new(Vec::new());
    &LOADED
}
