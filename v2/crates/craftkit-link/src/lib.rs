//! `craftkit-link` — the wiring between an application and its plugins.
//!
//! # What it does
//!
//! **The dependency list is the plugin list.**
//!
//! A plugin crate has to be a dependency of the application — that is what
//! "linked in" means — but the application should not have to *name* it.
//! Rust drops a dependency that nothing refers to, and a dropped
//! dependency takes its registrations with it, so something has to refer to
//! it.
//!
//! This reads the application's own manifest, finds the dependencies that
//! are plugins, and writes the references:
//!
//! ```text
//! use craftkit_plugin_hello as _;
//! ```
//!
//! So the wiring is **generated from the manifest**, and the manifest is
//! the only place a plugin is written down. Adding a plugin is one line in
//! `Cargo.toml` and nothing anywhere else.
//!
//! # Why it is a crate and not a copy
//!
//! Because it is needed by every application that has plugins, and a copy
//! of it in two places is two places for the two copies to disagree. This
//! is a **build dependency**: it is compiled for the build script, and it
//! is not in the application's own dependency list.

#![deny(
    clippy::unwrap_used,
    clippy::expect_used,
    clippy::panic,
    clippy::unimplemented,
    clippy::todo,
    clippy::unreachable
)]
#![forbid(unsafe_code)]

use std::path::Path;

/// The prefix a dependency's name has to have to be a plugin.
const PLUGIN_PREFIX: &str = "craftkit-plugin-";

/// Write the plugin references for a manifest, into a directory.
///
/// The file is `plugins.rs`, and the application includes it with
/// `include!(concat!(env!("OUT_DIR"), "/plugins.rs"))`.
pub fn generate(manifest: &Path, out_dir: &Path) -> Result<(), String> {
    let plugins = plugin_dependencies(manifest);
    let mut generated = String::new();
    generated.push_str("// Generated by craftkit-link. Do not edit.\n");
    generated.push_str("//\n");
    generated.push_str("// The plugins are the dependencies whose names begin with ");
    generated.push_str(PLUGIN_PREFIX);
    generated.push_str(".\n\n");
    for plugin in &plugins {
        // The reference that keeps the crate in the binary. Without it the
        // linker drops the crate, and the crate's registrations go with it.
        generated.push_str("use ");
        generated.push_str(&plugin.replace('-', "_"));
        generated.push_str(" as _;\n");
    }
    let out = out_dir.join("plugins.rs");
    std::fs::write(&out, generated).map_err(|error| format!("could not write {}: {error}", out.display()))
}

/// The plugin dependencies of a manifest.
///
/// A manifest is not a table this program can trust: it is a file a person
/// wrote. So this reads it as **text**, and looks for the lines that name
/// a plugin.
pub fn plugin_dependencies(manifest: &Path) -> Vec<String> {
    let Ok(text) = std::fs::read_to_string(manifest) else { return Vec::new() };
    let mut plugins: Vec<String> = Vec::new();
    let mut in_dependencies = false;
    for line in text.lines() {
        let line = line.trim();
        if line.starts_with('[') {
            in_dependencies = line == "[dependencies]";
            continue;
        }
        if !in_dependencies || line.starts_with('#') {
            continue;
        }
        let Some((name, _)) = line.split_once('=') else { continue };
        let name = name.trim().trim_matches('"');
        if name.starts_with(PLUGIN_PREFIX) && !plugins.contains(&name.to_string()) {
            plugins.push(name.to_string());
        }
    }
    plugins
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_plugin_dependency_is_found() {
        let dir = std::env::temp_dir().join("craftkit-link-test");
        std::fs::create_dir_all(&dir).expect("the directory is made");
        let manifest = dir.join("Cargo.toml");
        std::fs::write(
            &manifest,
            "[package]\nname = \"thing\"\n\n[dependencies]\ncraftkit-plugin-hello = { path = \"../x\" }\nserde_json = \"1\"\n",
        )
        .expect("the manifest is written");
        let plugins = plugin_dependencies(&manifest);
        assert_eq!(plugins, vec!["craftkit-plugin-hello".to_string()]);
        let _ = std::fs::remove_file(&manifest);
    }

    #[test]
    fn a_dependency_that_is_not_a_plugin_is_not_found() {
        let dir = std::env::temp_dir().join("craftkit-link-test-2");
        std::fs::create_dir_all(&dir).expect("the directory is made");
        let manifest = dir.join("Cargo.toml");
        std::fs::write(&manifest, "[dependencies]\nserde_json = \"1\"\n").expect("the manifest is written");
        assert!(plugin_dependencies(&manifest).is_empty());
        let _ = std::fs::remove_file(&manifest);
    }
}
