//! The **glyph table**: the kit's own typeface, written down as strokes.
//!
//! Every glyph is a set of **polylines** on a small grid, and the grid is
//! the same for every glyph:
//!
//! - the **baseline** is `y = 0`;
//! - the **cap height** is `y = 2` — the top of a capital letter;
//! - the **x-height** is `y = 1.5` — the top of a small letter;
//! - the **descender** is `y = -0.5` — the bottom of a `g` or a `p`.
//!
//! The `x` axis is the writing direction, and each glyph says how much
//! of it it takes: that is the **advance**, and it is in grid units like
//! everything else.
//!
//! These are **the kit's own letters**. They are drawn here, in code,
//! from coordinates chosen for this tree — the same rule the icons
//! follow: no artwork, no font file, nothing that is not a number in a
//! source file. They are plain: a capital is a skeleton of straight
//! strokes and a small letter is the same skeleton at two thirds of the
//! height, which is what a plotter font is and what a monoline
//! engraving is.

/// One glyph: how wide it is, and the strokes it is drawn with.
///
/// The strokes are **grid units** and the caller scales them: a glyph is
/// the same shape at every size, and a size is a number the caller
/// brings.
#[derive(Clone, Debug, PartialEq)]
pub struct Glyph {
    /// The glyph's width, in grid units.
    pub advance: f64,
    /// The strokes, each a list of points, each point an `x` and a `y`.
    pub strokes: Vec<Vec<[f64; 2]>>,
}

/// One entry of the table: a character, its advance and its strokes.
pub struct Entry {
    /// The character the glyph is for.
    pub character: char,
    /// The glyph.
    pub glyph: Glyph,
}

