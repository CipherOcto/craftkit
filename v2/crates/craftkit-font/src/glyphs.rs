/// The table, read: every character and its glyph.
///
/// The **raw** table is a list of tuples, because a list of tuples is a
/// constant and a constant is a table that cannot be got wrong at
/// runtime. This function reads it into the shape the callers use.
pub fn entries() -> Vec<Entry> {
    TABLE
        .iter()
        .map(|(character, advance, strokes)| {
            let strokes = strokes
                .iter()
                .map(|stroke| stroke.as_chunks::<2>().0.iter().map(|pair| [pair[0], pair[1]]).collect())
                .collect();
            let mut characters = character.chars();
            let first = characters.next().unwrap_or(' ');
            Entry { character: first, glyph: Glyph { advance: *advance, strokes } }
        })
        .collect()
}
