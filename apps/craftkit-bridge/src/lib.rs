// The plugins. Generated by the build script from the dependency list, so
// this program names no plugin and does not have to change when one is
// added.
//
// They are in the **library** and not only in the binary, so that the
// library's own tests see the same registry the program does.
include!(concat!(env!("OUT_DIR"), "/plugins.rs"));

use craftkit_sdk::serde_json::{Value as Json, json};
use craftkit_sdk::{Ecosystem, EngineError, MenuNode, Session};

/// The name this server calls itself.
pub const SERVER_NAME: &str = "craftkit-bridge";

/// The version of the protocol this server speaks.
pub const PROTOCOL_VERSION: &str = "2025-06-18";

/// A request that came in.
#[derive(Debug, Clone)]
pub struct Request {
    /// The id the answer carries back.
    pub id: Option<Json>,
    /// What is being asked.
    pub method: String,
    /// The arguments.
    pub params: Json,
}

impl Request {
    /// Read one request.
    ///
    /// A message that is not a request — a response, a notification with
    /// no id, a line of nonsense — is **not** a request, and the reader
    /// says so rather than guessing.
    pub fn parse(line: &str) -> Result<Self, String> {
        let value: Json =
            craftkit_sdk::serde_json::from_str(line).map_err(|error| format!("not JSON: {error}"))?;
        let method = value
            .get("method")
            .and_then(|method| method.as_str())
            .ok_or_else(|| "there is no method".to_string())?
            .to_string();
        Ok(Request {
            id: value.get("id").cloned(),
            method,
            params: value.get("params").cloned().unwrap_or(Json::Null),
        })
    }
}

/// A server: an ecosystem and a session over it.
pub struct Bridge {
    ecosystem: Ecosystem,
    session: Session,
}

impl Bridge {
    /// A bridge over an ecosystem.
    pub fn new(ecosystem: Ecosystem) -> Self {
        let session = ecosystem.session();
        Bridge { ecosystem, session }
    }

    /// The ecosystem the bridge is a view of.
    pub fn ecosystem(&self) -> &Ecosystem {
        &self.ecosystem
    }

    /// The session the bridge runs commands in.
    pub fn session(&mut self) -> &mut Session {
        &mut self.session
    }

    /// Answer one request.
    ///
    /// A method that is not there is an error, and the error says which
    /// methods are: an agent that asks for the wrong thing should be told
    /// what the right things are.
    pub fn handle(&mut self, request: &Request) -> Json {
        let result = match request.method.as_str() {
            "initialize" => Ok(self.initialize()),
            "tools/list" => Ok(self.tools()),
            "tools/call" => self.call(request),
            "resources/list" => Ok(self.resources()),
            "plan" => self.plan(),
            "journal" => Ok(self.journal()),
            "menu" => Ok(self.menu()),
            "shutdown" => Ok(json!({ "stopping": true })),
            other => Err(format!(
                "there is no method `{other}`: the methods are initialize, tools/list, tools/call, \
                 resources/list, plan, journal, menu and shutdown"
            )),
        };
        match result {
            Ok(result) => json!({
                "jsonrpc": "2.0",
                "id": request.id.clone().unwrap_or(Json::Null),
                "result": result,
            }),
            Err(message) => json!({
                "jsonrpc": "2.0",
                "id": request.id.clone().unwrap_or(Json::Null),
                "error": { "code": -32601, "message": message },
            }),
        }
    }

    /// What this server is.
    fn initialize(&self) -> Json {
        json!({
            "protocolVersion": PROTOCOL_VERSION,
            "serverInfo": { "name": SERVER_NAME, "version": env!("CARGO_PKG_VERSION") },
            "capabilities": { "tools": { "listChanged": false } },
        })
    }

    /// The commands, as tools.
    ///
    /// The **descriptor** gives the shape of a command, and the
    /// **session** says which commands there are: the list is read from
    /// the session the tools are run in, so a door never offers a tool the
    /// session does not have.
    ///
    /// The list is **pruned** to what this door shows: the commands, the
    /// effects and the tools. A command outside the pruning is a command
    /// this door does not show — and the registry stays whole. A command
    /// outside the pruning is **not runnable through this door** — the
    /// door runs only what it lists.
    fn tools(&self) -> Json {
        let tools: Vec<Json> = self
            .session
            .registry()
            .all()
            .iter()
            .filter(|command| matches!(command.capability, "command" | "effect" | "tool"))
            .map(|command| {
                let mut schema = craftkit_sdk::Projection::describe(command);
                let doc = schema.get("doc").cloned().unwrap_or(Json::Null);
                if let Some(object) = schema.as_object_mut() {
                    object.insert("name".to_string(), Json::String(command.id.to_string()));
                    object.insert("description".to_string(), doc);
                }
                schema
            })
            .collect();
        json!({ "tools": tools })
    }

    /// Run one command.
    ///
    /// Only a command the door **lists** can be run: the tool list is
    /// what an agent was told, and running something that was not on it
    /// is running a command the door did not offer.
    fn call(&mut self, request: &Request) -> Result<Json, String> {
        let name = request
            .params
            .get("name")
            .and_then(|name| name.as_str())
            .ok_or_else(|| "a call needs the name of the command".to_string())?;
        if !self.offers(name) {
            return Err(format!("there is no tool `{name}`"));
        }
        let arguments = request.params.get("arguments").cloned().unwrap_or_else(|| json!({}));
        match self.session.execute(name, &arguments) {
            Ok(outcome) => Ok(json!({
                "content": [{ "type": "text", "text": outcome.message }],
                "data": outcome.data,
                "isError": false,
            })),
            Err(error) => Err(engine_error_text(name, &error)),
        }
    }

    /// Whether this door offers a command.
    ///
    /// The **same** set as the tool list: the commands, the effects and
    /// the tools. A command outside it is not on the list, and a door
    /// that ran it would be running something it did not offer.
    fn offers(&self, id: &str) -> bool {
        self.session
            .registry()
            .all()
            .iter()
            .any(|command| command.id == id && matches!(command.capability, "command" | "effect" | "tool"))
    }

    /// The kinds, the formats and the **manifest**.
    ///
    /// The manifest is the projection's own door: it names every command,
    /// kind, tool, evaluator and panel with its layer and its line about
    /// itself. The bridge does not reach into a registry of its own to
    /// find the evaluator's ids — a front end that does that has a second
    /// path into the design.
    ///
    /// The **commands** in it are the session's: a command that joined the
    /// session while the program runs is in the manifest, because the
    /// manifest and the tool list are the same list.
    fn resources(&self) -> Json {
        let projection = self.ecosystem.projection();
        json!({
            "kinds": projection.kinds().iter().map(|kind| json!({
                "kind": kind.kind,
                "label": kind.label,
                "layer": kind.layer,
            })).collect::<Vec<_>>(),
            "formats": self.ecosystem.formats.ids(),
            "manifest": projection.manifest_with(self.session.registry()),
        })
    }

    /// What the document means right now.
    ///
    /// It is the **command's** work: the bridge asks `doc.plan` for it,
    /// the way every other door does, so every door says the same thing
    /// about the same document.
    fn plan(&mut self) -> Result<Json, String> {
        match self.session.execute("doc.plan", &json!({})) {
            Ok(outcome) => Ok(outcome.data),
            Err(error) => Err(engine_error_text("doc.plan", &error)),
        }
    }

    /// The **journal**: what this session was asked to do.
    ///
    /// It is a program, and it can be run again: an agent that drove the
    /// program can hand the journal to `journal.replay` and have it done
    /// again.
    fn journal(&self) -> Json {
        json!({ "entries": self.session.journal().iter().map(|entry| entry.to_json()).collect::<Vec<_>>() })
    }

    /// The **menu**, as a tree.
    ///
    /// The same view the studio's menu is made of, and made of the
    /// **session** the commands run in — so the menu and the tool list
    /// come from one registry, and the two cannot disagree.
    fn menu(&self) -> Json {
        let tree = self.session.registry().menu_tree(&["command", "effect", "tool"]);
        json!({ "menu": tree.iter().map(MenuNode::to_json).collect::<Vec<_>>() })
    }
}

/// The text of an engine error.
///
/// A refusal is not a crash: the message says what was refused and why,
/// and the agent is told so.
fn engine_error_text(name: &str, error: &EngineError) -> String {
    format!("`{name}` was refused: {error}")
}

/// Serve the bridge over the standard input and output.
///
/// One message per line, in and out. A line that is not a request is
/// **ignored** rather than answered, because a stream may carry anything.
/// The most bytes a line of the bridge may hold.
const MAX_LINE_BYTES: craftkit_sdk::lines::LineLimit = 1024 * 1024;

pub fn serve(mut bridge: Bridge) {
    let stdin = std::io::stdin();
    let stdout = std::io::stdout();
    let mut out = stdout.lock();
    for line in craftkit_sdk::lines::lines_bounded(stdin.lock(), MAX_LINE_BYTES) {
        let Ok(line) = line else { break };
        if line.trim().is_empty() {
            continue;
        }
        let Ok(request) = Request::parse(&line) else { continue };
        let answer = bridge.handle(&request);
        let _ = writeln!(out, "{answer}");
        let _ = out.flush();
        if request.method == "shutdown" {
            break;
        }
    }
}

