use std::sync::{Arc, Mutex};

use craftkit_sdk::serde_json::{Value as Json, json};
use craftkit_sdk::{Ecosystem, Outcome, Session};

/// The name this door calls itself.
pub const SERVER_NAME: &str = "craftkit-a2ui-server";

/// The version of a2ui's protocol this door speaks.
///
/// **One** version: the door says which one it speaks, and it refuses a
/// request that names another — so the version it says is the version it
/// accepts.
pub const PROTOCOL_VERSION: &str = craftkit_a2ui::catalog::PROTOCOL_VERSION;

/// The methods a2ui's protocol defines, and the one the transport adds.
pub const METHODS: &[&str] = &[
    "initialize",
    "createSurface",
    "updateComponents",
    "updateDataModel",
    "deleteSurface",
    "callRendererFunction",
    "agentFunctionResponse",
];

/// A request that came in.
#[derive(Debug, Clone)]
pub struct Request {
    /// The id the answer carries back.
    pub id: Option<Json>,
    /// What is being asked.
    pub method: String,
    /// The arguments.
    pub params: Json,
}

impl Request {
    /// Read one request.
    ///
    /// A message that is not a request — a response, a line of nonsense —
    /// is **not** a request, and the reader says so rather than guessing.
    pub fn parse(line: &str) -> Result<Self, String> {
        let value: Json =
            craftkit_sdk::serde_json::from_str(line).map_err(|error| format!("not JSON: {error}"))?;
        let method = value
            .get("method")
            .and_then(|method| method.as_str())
            .ok_or_else(|| "there is no method".to_string())?
            .to_string();
        Ok(Request {
            id: value.get("id").cloned(),
            method,
            params: value.get("params").cloned().unwrap_or(Json::Null),
        })
    }
}

/// The messages the door has to send and that are **not** replies.
///
/// The door's own stream and the door's **control channel** share one
/// queue: a click on the channel may raise an action, and the action
/// belongs on the wire the agent is reading.
///
/// The queue is a **channel**, and not a vector behind a lock: the
/// writer that owns the standard output waits on it, so an action that
/// is raised while the agent says nothing is still written.
pub type Outbound = std::sync::mpsc::Sender<Option<Json>>;

/// The surfaces that asked for their **data model** to be sent.
///
/// The protocol says a surface that asked for its model gets it in the
/// metadata of **every** message the door sends to the agent — so the
/// answer is a fact about the surface, and the door and its render have
/// to agree on it: they share this.
#[derive(Clone, Default)]
pub struct Surfaces(Arc<Mutex<std::collections::BTreeMap<String, bool>>>);

impl Surfaces {
    /// A surface that asked for its **data model** to be sent.
    pub fn ask(&self, surface_id: &str) {
        let mut surfaces = match self.0.lock() {
            Ok(surfaces) => surfaces,
            Err(poisoned) => poisoned.into_inner(),
        };
        surfaces.insert(surface_id.to_string(), true);
    }

    /// Whether **any** surface asked for its data model.
    pub fn any(&self) -> bool {
        let surfaces = match self.0.lock() {
            Ok(surfaces) => surfaces,
            Err(poisoned) => poisoned.into_inner(),
        };
        surfaces.values().any(|asked| *asked)
    }

    /// The surfaces that asked, and their names.
    pub fn asked(&self) -> Vec<String> {
        let surfaces = match self.0.lock() {
            Ok(surfaces) => surfaces,
            Err(poisoned) => poisoned.into_inner(),
        };
        surfaces.iter().filter(|(_, asked)| **asked).map(|(surface_id, _)| surface_id.clone()).collect()
    }
}

/// A **failure**, and what kind it is.
///
/// The JSON-RPC codes say what went wrong: a method that is not there,
/// a request that is wrong, and a command that was refused are three
/// different things, and a client that cannot tell them apart cannot
/// say what to do.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Fault {
    /// There is no such method.
    Method(String),
    /// The request is wrong.
    Params(String),
    /// The command was refused.
    Refused(String),
}

impl Fault {
    /// The JSON-RPC code for the fault.
    pub fn code(&self) -> i64 {
        match self {
            Fault::Method(_) => -32601,
            Fault::Params(_) => -32602,
            Fault::Refused(_) => -32000,
        }
    }

    /// What the fault says.
    pub fn message(&self) -> &str {
        match self {
            Fault::Method(message) | Fault::Params(message) | Fault::Refused(message) => message,
        }
    }
}

impl From<String> for Fault {
    fn from(message: String) -> Self {
        Fault::Params(message)
    }
}

/// The door: an ecosystem and a session over it.
pub struct Server {
    ecosystem: Ecosystem,
    /// The door's **own** session — behind a lock, because the control
    /// channel serves the very same document and not a copy of it.
    session: Arc<Mutex<Session>>,
    /// The messages that are not replies.
    outbound: Outbound,
    /// The other end of the queue, for the **writer**.
    ///
    /// The writer takes it when the door is served, and the door's own
    /// tests take the messages out of it.
    outbound_rx: Mutex<Option<std::sync::mpsc::Receiver<Option<Json>>>>,
    /// Whether the agent has said it accepts an **inline** catalogue.
    ///
    /// The default is **false** — a2ui's own default — and the door may
    /// only publish an inline catalogue once the agent has said yes.
    accepts_inline_catalogs: bool,
    /// Whether the agent has said it accepts a catalogue **by file**.
    accepts_catalog_files: bool,
    /// How many calls to the agent the door has made.
    ///
    /// The protocol says every call to an agent-side function carries an
    /// id of its own, and the agent copies it into the answer.
    calls: std::sync::atomic::AtomicU64,
    /// The surfaces that asked for their **data model** to be sent.
    surfaces: Surfaces,
}

impl Server {
    /// A door over an ecosystem.
    pub fn new(ecosystem: Ecosystem) -> Self {
        let session = Arc::new(Mutex::new(ecosystem.session()));
        let (outbound, outbound_rx) = std::sync::mpsc::channel();
        Server {
            ecosystem,
            session,
            outbound,
            outbound_rx: Mutex::new(Some(outbound_rx)),
            accepts_inline_catalogs: false,
            accepts_catalog_files: false,
            calls: std::sync::atomic::AtomicU64::new(0),
            surfaces: Surfaces::default(),
        }
    }

    /// The **session** the door runs commands in, behind its lock.
    pub fn with_session<T>(&mut self, body: impl FnOnce(&mut Session) -> T) -> T {
        let mut session = match self.session.lock() {
            Ok(session) => session,
            Err(poisoned) => poisoned.into_inner(),
        };
        body(&mut session)
    }

    /// The surfaces that asked for their **data model** to be sent.
    ///
    /// The render shares them: the metadata of a message is a fact
    /// about the surfaces, and the two must not disagree.
    pub fn surfaces(&self) -> Surfaces {
        self.surfaces.clone()
    }

    /// The **shared** session, for the control channel.
    ///
    /// The channel serves the door's own document, so a command an agent
    /// runs over the channel changes what the door is drawing.
    pub fn shared_session(&self) -> Arc<Mutex<Session>> {
        Arc::clone(&self.session)
    }

    /// The queue of the messages that are not replies.
    pub fn outbound(&self) -> Outbound {
        self.outbound.clone()
    }

    /// The messages that are **waiting** to go out.
    ///
    /// The door's own tests take them this way; the door itself hands
    /// the reader to the **writer**, and the writer waits on it.
    pub fn take_outbound(&self) -> Vec<Json> {
        let mut messages = Vec::new();
        let receiver = match self.outbound_rx.lock() {
            Ok(receiver) => receiver,
            Err(poisoned) => poisoned.into_inner(),
        };
        if let Some(receiver) = receiver.as_ref() {
            while let Ok(Some(message)) = receiver.try_recv() {
                messages.push(message);
            }
        }
        messages
    }

    /// Run a **command**, and queue any action it raises.
    ///
    /// A command whose outcome names an **action** has raised one for the
    /// agent, and the action is one of the door's outbound messages that
    /// are not replies to a call.
    fn run(&mut self, command: &str, params: &Json) -> Result<Outcome, craftkit_sdk::EngineError> {
        let outcome = self.with_session(|session| session.execute(command, params))?;
        if let Some(message) = self.outbound_message(&outcome) {
            // The message goes on the wire even if the agent says nothing
            // more: the writer waits on the queue.
            let _ = self.outbound.send(Some(message));
        }
        Ok(outcome)
    }

    /// The **message** a command's outcome raised, if it raised one.
    ///
    /// An **action** is the agent's, and a **call** to an agent-side
    /// function is the agent's too — and the two are different messages
    /// on the wire, because the protocol says they are.
    fn outbound_message(&mut self, outcome: &Outcome) -> Option<Json> {
        let call_id = self.next_call_id();
        let surfaces = self.surfaces.clone();
        let metadata = self.with_session(|session| metadata_of(&surfaces, session));
        message_of(outcome, &call_id, metadata)
    }

    /// The **next** id of a call to the agent.
    ///
    /// The protocol says the id is unique for the call, and the agent
    /// copies it into the answer — so the door counts them.
    fn next_call_id(&self) -> String {
        let count = self.calls.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
        format!("call-{count}")
    }

    /// The ecosystem the door is a view of.
    pub fn ecosystem(&self) -> &Ecosystem {
        &self.ecosystem
    }

    /// The **catalogue** the door serves: the projection of the
    /// `CatalogEntry` registry into a2ui's own shape.
    pub fn catalogue(&self) -> Result<Json, Fault> {
        let projection = self.ecosystem.projection();
        craftkit_a2ui::catalog::catalogue(&projection.entries()).map_err(Fault::Refused)
    }

    /// Answer one request.
    ///
    /// A method that is not there is an error, and the error says which
    /// methods are. A request that names another version of the protocol
    /// is refused — craftkit's rule, and not a2ui's adapter chain.
    ///
    /// A request with **no id** is a notification, and the **door** does
    /// not answer it: the answer would be a reply to nothing.
    pub fn handle(&mut self, request: &Request) -> Json {
        let result = match self.version_of(request) {
            Some(version) => Err(Fault::Params(format!(
                "the request names the protocol version `{version}`, and the door speaks only \
                 `{PROTOCOL_VERSION}`"
            ))),
            None => self.dispatch(request),
        };
        match result {
            Ok(result) => json!({
                "jsonrpc": "2.0",
                "id": request.id.clone().unwrap_or(Json::Null),
                "result": result,
            }),
            Err(fault) => json!({
                "jsonrpc": "2.0",
                "id": request.id.clone().unwrap_or(Json::Null),
                "error": { "code": fault.code(), "message": fault.message() },
            }),
        }
    }

    /// The **version** the request names, if it names one that is not
    /// the door's.
    ///
    /// The version may be in the message's own body — a2ui's envelope
    /// puts it there — or beside the method, and a request that names no
    /// version at all is the door's own.
    fn version_of(&self, request: &Request) -> Option<String> {
        let named = request
            .params
            .get("version")
            .and_then(Json::as_str)
            .or_else(|| request.params.get("messageVersion").and_then(Json::as_str));
        match named {
            Some(version) if version != craftkit_a2ui::catalog::PROTOCOL_VERSION => Some(version.to_string()),
            _ => None,
        }
    }

    /// Answer one request, once the version is known to be the door's.
    fn dispatch(&mut self, request: &Request) -> Result<Json, Fault> {
        match request.method.as_str() {
            "initialize" => self.initialize(request),
            "createSurface" => self.create_surface(request),
            "updateComponents" => self.update_components(request),
            "updateDataModel" => self.update_data_model(request),
            "deleteSurface" => self.delete_surface(request),
            "callRendererFunction" => self.call_renderer_function(request),
            "agentFunctionResponse" => self.agent_function_response(request),
            other => Err(Fault::Method(format!(
                "there is no method `{other}`: the methods are initialize, createSurface, \
                 updateComponents, updateDataModel, deleteSurface, callRendererFunction and \
                 agentFunctionResponse"
            ))),
        }
    }

    /// The **handshake**: the agent's capabilities up, the renderer's
    /// down.
    fn initialize(&mut self, request: &Request) -> Result<Json, Fault> {
        let capabilities = request.params.get("capabilities").cloned().unwrap_or(Json::Null);
        self.accepts_inline_catalogs =
            capabilities.get("acceptsInlineCatalogs").and_then(Json::as_bool).unwrap_or(false);
        self.accepts_catalog_files =
            capabilities.get("acceptsCatalogFiles").and_then(Json::as_bool).unwrap_or(false);
        if !self.accepts_inline_catalogs && !self.accepts_catalog_files {
            return Err(Fault::Params(
                "the agent accepts neither an inline catalogue nor a catalogue file, and the \
                 door has no third route"
                    .to_string(),
            ));
        }
        let mut renderer = json!({
            "supportedCatalogIds": [craftkit_a2ui::catalog::CATALOG_ID],
            "protocolVersion": craftkit_a2ui::catalog::PROTOCOL_VERSION,
        });
        if self.accepts_inline_catalogs {
            renderer["inlineCatalogs"] =
                json!([self.catalogue().map_err(|fault| fault.message().to_string())?]);
        }
        Ok(json!({
            "protocolVersion": PROTOCOL_VERSION,
            "serverInfo": { "name": SERVER_NAME, "version": env!("CARGO_PKG_VERSION") },
            "a2uiRendererCapabilities": renderer,
        }))
    }

    /// **`agentFunctionResponse`**: the agent's answer to a call the
    /// door made.
    ///
    /// The door **forwards** a call to an agent-side function, and the
    /// agent answers it — and the answer is a value the tree cannot
    /// yet put anywhere: a call's answer resolves the prop that made
    /// the call, and the tree does not resolve that yet.
    ///
    /// So the answer is **refused**, and not swallowed: the agent is
    /// told that its answer was not used, and why. A message that is
    /// dropped is a hole, and a hole that is named is a narrowing.
    fn agent_function_response(&mut self, request: &Request) -> Result<Json, Fault> {
        let response = request
            .params
            .get("agentFunctionResponse")
            .or_else(|| request.params.get("response"))
            .cloned()
            .ok_or_else(|| Fault::Params("there is no `agentFunctionResponse`".to_string()))?;
        let call_id = response
            .get("functionCallId")
            .and_then(Json::as_str)
            .ok_or_else(|| Fault::Params("there is no `functionCallId`".to_string()))?;
        Err(Fault::Refused(format!(
            "the answer to the call `{call_id}` is not used: the tree does not resolve the answer of              a call yet"
        )))
    }

    /// The **catalogue file**: the door writes it, and says where, **on
    /// stderr**.
    ///
    /// The file is **created**, and not opened: a path that is already
    /// there — a link, or another door's file — is refused, so the door
    /// never writes over something it did not make.
    pub fn write_catalogue(&self, path: &std::path::Path) -> Result<(), String> {
        let catalogue = self.catalogue().map_err(|fault| fault.message().to_string())?;
        let text = serde_json_to_string(&catalogue)?;
        // The file is **created**, and not opened: a path that is
        // already there — a link, or another door's file — is refused,
        // so the door never writes over something it did not make.
        let mut file = std::fs::File::create_new(path)
            .map_err(|error| format!("the catalogue was not written: {error}"))?;
        use std::io::Write;
        file.write_all(text.as_bytes()).map_err(|error| format!("the catalogue was not written: {error}"))
    }

    /// **`createSurface`**: make a surface, and the node it draws into.
    fn create_surface(&mut self, request: &Request) -> Result<Json, Fault> {
        let surface_id = request
            .params
            .get("surfaceId")
            .and_then(Json::as_str)
            .ok_or_else(|| Fault::Params("there is no `surfaceId`".to_string()))?
            .to_string();
        // The **catalogue** the surface names is the agent's choice — and
        // the door serves exactly one. An omitted one is the door's own;
        // a wrong one is refused.
        if let Some(catalog) = request.params.get("catalogId").and_then(Json::as_str)
            && catalog != craftkit_a2ui::catalog::CATALOG_ID
        {
            return Err(Fault::Params(format!(
                "the surface names the catalogue `{catalog}`, and the door serves only \
                     `{}`",
                craftkit_a2ui::catalog::CATALOG_ID
            )));
        }
        // **The extensions** are data craftkit does not know, and a
        // payload the tree cannot interpret has nowhere to go.
        if let Some(extensions) = request.params.get("metadata").and_then(|m| m.get("extensions"))
            && !extensions.is_null()
        {
            return Err(Fault::Params(
                "the surface carries `metadata.extensions`, and the door has nowhere to put \
                     them"
                    .to_string(),
            ));
        }
        // The **sendDataModel** flag asks the door to put the whole data
        // model in the metadata of every message it sends for this
        // surface — and the door holds the model, so it can. The flag
        // is remembered, because the messages are sent later.
        let send_data_model = request.params.get("sendDataModel").and_then(Json::as_bool).unwrap_or(false);
        if send_data_model {
            self.surfaces.ask(&surface_id);
        }
        let outcome = self
            .run("a2ui.surface.create", &json!({ "surface_id": surface_id }))
            .map_err(|error| Fault::Refused(error.to_string()))?;
        // The **initial data model** may come with the surface, and the
        // protocol says it is applied **first**: a component binds
        // against it on its first resolution.
        if let Some(model) = request.params.get("dataModel") {
            self.run("a2ui.data.set", &json!({ "surface_id": surface_id, "path": "", "value": model }))
                .map_err(|error| Fault::Refused(error.to_string()))?;
        }
        // And the **tree** may come with it too.
        if let Some(components) = request.params.get("components") {
            self.run("a2ui.surface.apply", &json!({ "surface_id": surface_id, "components": components }))
                .map_err(|error| Fault::Refused(error.to_string()))?;
        }
        let mut result = json!({ "surfaceId": surface_id });
        if send_data_model {
            result["dataModel"] = self.data_model(&surface_id);
        }
        let _ = outcome;
        Ok(result)
    }

    /// The surface's **data model**, as the metadata carries it.
    ///
    /// The model is the **surface's**, and it is in the document — so
    /// the door reads it from there, and not from a copy of its own.
    /// A surface that is not there has **no** model, and the metadata
    /// carries an empty one.
    fn data_model(&mut self, surface_id: &str) -> Json {
        self.with_session(|session| {
            let document = session.document();
            let surface =
                document.nodes().find(|node| node.kind == "a2ui.surface" && node.name == surface_id);
            match surface {
                Some(surface) => {
                    surface.data.get("model").cloned().unwrap_or(Json::Object(Default::default()))
                }
                None => Json::Object(Default::default()),
            }
        })
    }

    /// **`updateComponents`**: the component tree → the layer's nodes →
    /// the document, **through commands**.
    fn update_components(&mut self, request: &Request) -> Result<Json, Fault> {
        let surface_id = request
            .params
            .get("surfaceId")
            .and_then(Json::as_str)
            .ok_or_else(|| Fault::Params("there is no `surfaceId`".to_string()))?
            .to_string();
        let components = request
            .params
            .get("components")
            .cloned()
            .ok_or_else(|| Fault::Params("there are no `components`".to_string()))?;
        self.run("a2ui.surface.apply", &json!({ "surface_id": surface_id, "components": components }))
            .map_err(|error| Fault::Refused(error.to_string()))?;
        Ok(json!({ "surfaceId": surface_id }))
    }

    /// **`updateDataModel`**: the crate's tree.
    fn update_data_model(&mut self, request: &Request) -> Result<Json, Fault> {
        let surface_id = request
            .params
            .get("surfaceId")
            .and_then(Json::as_str)
            .ok_or_else(|| Fault::Params("there is no `surfaceId`".to_string()))?
            .to_string();
        let contents = request
            .params
            .get("contents")
            .cloned()
            .ok_or_else(|| Fault::Params("there are no `contents`".to_string()))?;
        self.run("a2ui.data.set", &json!({ "surface_id": surface_id, "path": "", "value": contents }))
            .map_err(|error| Fault::Refused(error.to_string()))?;
        Ok(json!({ "surfaceId": surface_id }))
    }

    /// **`deleteSurface`**: remove the surface's nodes, **through
    /// commands**.
    fn delete_surface(&mut self, request: &Request) -> Result<Json, Fault> {
        let surface_id = request
            .params
            .get("surfaceId")
            .and_then(Json::as_str)
            .ok_or_else(|| Fault::Params("there is no `surfaceId`".to_string()))?
            .to_string();
        self.run("a2ui.surface.delete", &json!({ "surface_id": surface_id }))
            .map_err(|error| Fault::Refused(error.to_string()))?;
        Ok(json!({ "surfaceId": surface_id }))
    }

    /// **`callRendererFunction`**: the agent asks the renderer to do
    /// something local.
    ///
    /// The layer's **own** functions run through `Session::execute`, and
    /// a name that is in neither table is **refused** — the protocol's
    /// own default is a fallback to the agent, and craftkit's rule is
    /// that an unknown name is refused.
    fn call_renderer_function(&mut self, request: &Request) -> Result<Json, Fault> {
        let name = request
            .params
            .get("name")
            .and_then(Json::as_str)
            .ok_or_else(|| Fault::Params("there is no `name`".to_string()))?
            .to_string();
        if craftkit_a2ui::functions::is_reserved(&name) {
            return Err(Fault::Params(format!(
                "the function `{name}` is reserved, and the door implements no reserved function"
            )));
        }
        let Some(command) = craftkit_a2ui::functions::command_of(&name) else {
            return Err(Fault::Params(format!(
                "the function `{name}` is in neither the layer's table nor the agent-side table"
            )));
        };
        let args = request.params.get("args").cloned().unwrap_or(Json::Null);
        // The arguments are **translated**: a2ui says `surfaceId` and
        // craftkit says `surface_id`, and the layer's table says which
        // is which — so the names are translated and not guessed, and an
        // argument the table does not name is refused.
        let args = translate(&name, &args).map_err(Fault::Params)?;
        self.run(command, &args).map_err(|error| Fault::Refused(error.to_string()))?;
        Ok(json!({ "name": name }))
    }
}

/// The **arguments** of a call, in craftkit's own names.
///
/// a2ui says `surfaceId` and craftkit says `surface_id`, and the
/// layer's table says which is which — so the names are **translated**,
/// not guessed. An argument the table does not name is **refused**: a
/// name that is not known is a name that is not used.
pub fn translate(name: &str, args: &Json) -> Result<Json, String> {
    let Some(pairs) = craftkit_a2ui::functions::arguments_of(name) else {
        return Err(format!("the function `{name}` takes no arguments"));
    };
    let Some(object) = args.as_object() else {
        if args.is_null() {
            return Ok(Json::Object(Default::default()));
        }
        return Err(format!("the arguments of `{name}` are not an object"));
    };
    let mut out = craftkit_sdk::serde_json::Map::new();
    for (key, value) in object {
        let Some((_, craftkit_name)) = pairs.iter().find(|(a2ui, _)| a2ui == key) else {
            return Err(format!("`{key}` is not an argument of `{name}`"));
        };
        out.insert((*craftkit_name).to_string(), value.clone());
    }
    // And the arguments the function **must** be given: a call that
    // leaves one out is a wrong request, and the door says so before
    // it runs anything.
    for required in craftkit_a2ui::functions::required_of(name).unwrap_or(&[]) {
        if !object.contains_key(*required) {
            return Err(format!("`{required}` is an argument of `{name}` and it is not there"));
        }
    }
    Ok(Json::Object(out))
}

/// The **message** a command's outcome raised, if it raised one.
///
/// An **action** is the agent's, and a **call** to an agent-side
/// function is the agent's too — and the two are different messages on
/// the wire, because the protocol says they are.
pub fn message_of(outcome: &Outcome, call_id: &str, metadata: Option<Json>) -> Option<Json> {
    let (method, params) = match outcome.data.get("action") {
        Some(action) => {
            let mut action = action.as_object()?.clone();
            action.insert("timestamp".to_string(), json!(timestamp()));
            ("action", json!({ "version": "1.0", "action": action }))
        }
        None => {
            let call = outcome.data.get("callAgentFunction")?;
            let mut call = call.as_object()?.clone();
            call.insert("functionCallId".to_string(), json!(call_id));
            ("callAgentFunction", json!({ "version": "1.0", "callAgentFunction": call }))
        }
    };
    // The **metadata** goes with the message and not inside it: the
    // protocol's own message holds the version and the one payload, and
    // nothing else — so the data model rides **beside** the params, in
    // the transport's own envelope.
    let mut message = json!({ "jsonrpc": "2.0", "method": method, "params": params });
    if let Some(metadata) = metadata {
        message["metadata"] = metadata;
    }
    Some(message)
}

/// The **metadata** of a message: the data models of the surfaces that
/// asked for them.
///
/// The protocol's own shape: the a2uiRendererDataModel object, with a
/// map of surface ids to their models. And a surface that asked and is
/// not there any more has **no** model to send.
fn metadata_of(surfaces: &Surfaces, session: &Session) -> Option<Json> {
    let asked = surfaces.asked();
    if asked.is_empty() {
        return None;
    }
    let document = session.document();
    let mut models = craftkit_sdk::serde_json::Map::new();
    for surface_id in asked {
        let model = document
            .nodes()
            .find(|node| node.kind == "a2ui.surface" && node.name == surface_id)
            .and_then(|node| node.data.get("model").cloned())
            .unwrap_or(Json::Object(Default::default()));
        models.insert(surface_id, model);
    }
    Some(json!({
        "a2uiRendererDataModel": { "version": "1.0", "surfaces": Json::Object(models) },
    }))
}

/// The **action** a command raised, as the door's outbound message.
///
/// The action travels in the command's outcome, so the door does not
/// have to read it back out of a message. The message is a2ui's own: the
/// action, with the surface it came from, the component that raised it,
/// the time, and the context.
pub fn action_message(outcome: &Outcome) -> Option<Json> {
    let action = outcome.data.get("action")?;
    let mut action = action.as_object()?.clone();
    action.insert("timestamp".to_string(), json!(timestamp()));
    Some(json!({
        "jsonrpc": "2.0",
        "method": "action",
        "params": { "version": "1.0", "action": action },
    }))
}

/// The **action** a command raised, as the door's outbound message — and
/// the metadata it carries, if any.
pub fn action_message_with(outcome: &Outcome, metadata: Option<Json>) -> Option<Json> {
    let mut message = action_message(outcome)?;
    if let Some(metadata) = metadata {
        message["params"]["metadata"] = metadata;
    }
    Some(message)
}

/// **Now**, as an ISO 8601 timestamp.
///
/// The door is an application and not a library, so it may ask the
/// machine what time it is — and the tree itself has no clock.
pub fn timestamp() -> String {
    let seconds = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|since| since.as_secs() as i64)
        .unwrap_or(0);
    let days = seconds.div_euclid(86_400);
    let time = seconds.rem_euclid(86_400);
    let (year, month, day) = civil_from_days(days);
    format!("{year:04}-{month:02}-{day:02}T{:02}:{:02}:{:02}Z", time / 3600, (time % 3600) / 60, time % 60)
}

/// The **date** of a count of days since the epoch.
///
/// The days-from-civil inverse, by Howard Hinnant's algorithm: the
/// count is shifted so that the year starts on 1 March, and the leap
/// day falls at the end of the year.
fn civil_from_days(days: i64) -> (i64, u32, u32) {
    let shifted = days + 719_468;
    let era = if shifted >= 0 { shifted } else { shifted - 146_096 } / 146_097;
    let day_of_era = shifted - era * 146_097;
    let year_of_era = (day_of_era - day_of_era / 1460 + day_of_era / 36_524 - day_of_era / 146_096) / 365;
    let year = year_of_era + era * 400;
    let day_of_year = day_of_era - (365 * year_of_era + year_of_era / 4 - year_of_era / 100);
    let shifted_month = (5 * day_of_year + 2) / 153;
    let day = (day_of_year - (153 * shifted_month + 2) / 5 + 1) as u32;
    let month = if shifted_month < 10 { shifted_month + 3 } else { shifted_month - 9 } as u32;
    let year = if month <= 2 { year + 1 } else { year };
    (year, month, day)
}

/// The catalogue as **text**, for the file.
fn serde_json_to_string(value: &Json) -> Result<String, String> {
    craftkit_sdk::serde_json::to_string_pretty(value)
        .map_err(|error| format!("the catalogue was not written: {error}"))
}

/// The most bytes one request may hold.
///
/// A line that is over the limit is **refused**: the door reads a line
/// byte by byte, so the limit is checked as it goes and not after the
/// whole line has been in memory.
pub const MAX_A2UI_LINE: usize = 1024 * 1024;

/// Serve the door: one JSON-RPC message per line, in and out.
///
/// **One writer owns the standard output.** The answers and the
/// messages that are not replies go through the same writer, so the
/// lines never interleave — and a message that is raised while the
/// agent says nothing is still written, because the writer waits on the
/// queue.
pub fn serve(server: Server) {
    let stdin = std::io::stdin();
    let stdout = std::io::stdout();
    serve_with(server, stdin.lock(), stdout);
}

/// Serve the door over **these** streams.
///
/// The streams are the parameters, and not the standard ones, so that
/// the door's own loop can be driven by a test.
pub fn serve_with(
    mut server: Server,
    input: impl std::io::BufRead,
    output: impl std::io::Write + Send + 'static,
) {
    // The **writer** takes the reader's end of the queue: it owns the
    // output, and every message — the answers and the messages that are
    // not replies — goes through it, so the lines never interleave.
    let receiver = match server.outbound_rx.lock() {
        Ok(mut receiver) => receiver.take(),
        Err(poisoned) => poisoned.into_inner().take(),
    };
    let Some(receiver) = receiver else { return };
    let writing = std::thread::spawn(move || {
        let mut output = output;
        while let Ok(message) = receiver.recv() {
            let Some(message) = message else { break };
            let _ = writeln!(output, "{message}");
            let _ = output.flush();
        }
    });
    for line in craftkit_sdk::lines::lines_bounded(input, MAX_A2UI_LINE) {
        let Ok(line) = line else { break };
        if line.trim().is_empty() {
            continue;
        }
        let answer = match Request::parse(&line) {
            // A **notification** — a request with no id — is not
            // answered: the answer would be a reply to nothing.
            Ok(request) => {
                if request.id.is_none() {
                    continue;
                }
                server.handle(&request)
            }
            Err(message) => json!({
                "jsonrpc": "2.0",
                "id": Json::Null,
                "error": { "code": -32700, "message": message },
            }),
        };
        let _ = server.outbound.send(Some(answer));
    }
    // The writer ends when it is **told** to: the door is done.
    let _ = server.outbound.send(None);
    drop(server);
    let _ = writing.join();
}

