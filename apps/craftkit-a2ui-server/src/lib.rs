//! `craftkit-a2ui-server` — the **a2ui door**.
//!
//! # What this is
//!
//! A **stdio JSON-RPC door** that speaks **a2ui**: an agent sends a2ui's
//! messages, and craftkit draws them.
//!
//! It is a **front end** over the same registry as every other door, and
//! it is **thin**: it reads the kit's state and acts through the
//! registry. It never writes to the document, never calls the evaluator,
//! and never keeps a value the evaluator computes — every change is a
//! **command**, run through `Session::execute`.
//!
//! # The **method names** are a2ui's
//!
//! A JSON-RPC method is a string, and the door uses the **a2ui message
//! name** as the method name — `createSurface`, `updateComponents`,
//! `updateDataModel`, `deleteSurface`, `callRendererFunction`,
//! `agentFunctionResponse` — so a reader of the wire sees a2ui's
//! vocabulary and not a second one.
//!
//! **`initialize` is the one name that is not a2ui's**, because the
//! handshake is the transport's.
//!
//! # The handshake is **two-way**
//!
//! JSON-RPC 2.0 has nowhere to put "transport metadata", and a2ui
//! exchanges its capabilities in transport metadata or in a transport's
//! own handshake — a2ui's own text names the precedent (*"initialization
//! in MCP"*, `specification/v1_0/docs/a2ui_protocol.md:93`). So:
//!
//! - the **request** carries the **agent's** capabilities, because the
//!   door must know what the agent accepts **before** it can answer; and
//! - the **result** carries the **`a2uiRendererCapabilities** — the
//!   renderer's — with the inline catalogue **only** if the agent said
//!   `acceptsInlineCatalogs: true` (the default is **false**).
//!
//! # The catalogue has **two** routes
//!
//! | the route | how | who it needs |
//! |---|---|---|
//! | **inline** | the capabilities' `inlineCatalogs` | an agent that says `acceptsInlineCatalogs: true` |
//! | **the file** | the door writes the catalogue to a **stated path** and writes **that path to stderr** | a host that can read a file |
//!
//! **Never to stdout**: stdout carries the JSON-RPC stream, and a line of
//! text there corrupts it.
//!
//! **And an agent that accepts neither is refused**, with the reason: the
//! door has no third route, and the protocol has no message that carries
//! a catalogue.
//!
//! # The door **serves** its own session on a **control channel**
//!
//! Every app has its own session, so the door's document is not the
//! window's document and nothing shares it — and the door serves **its
//! own** session on a control channel, so that a client can see what the
//! program is showing. The channel needs a `Render`, and the door's is
//! the **headless** one: a software rasteriser, a click, and a drag.
//! There is **no window**: the picture is drawn by the rasteriser, and a
//! window that attaches to somebody else's session is not in the tree.
//!
//! # The messages that are **not** replies
//!
//! A component's action may be the **agent's** — an event, or a function
//! the layer does not implement. Then the door sends an **`action`**
//! message, or a **`callAgentFunction`** message when the agent is to
//! run a function. Those are the door's outbound messages that are not
//! replies to a call, and the action travels in the command's outcome,
//! so the door puts it on the wire.
//!
//! # The **data model** rides in the metadata
//!
//! a2ui says a surface that asked for its data model gets it in the
//! metadata of **every** message the door sends — and the transport's
//! metadata mechanism is the transport's own business, so the door puts
//! it in a `metadata` member of the message's params, and the payload is
//! the protocol's own `a2uiRendererDataModel` object.
//!
//! And a surface may carry its **tree** and its **data model** in the
//! `createSurface` that makes it: the model is applied **first**, so
//! that a component binds against it on its first resolution.
//!
//! # The answer to a **call** is not used, and says so
//!
//! The door forwards a call to an agent-side function, and the agent
//! answers it. The answer would resolve the prop that made the call —
//! and the tree does not resolve that yet. So the answer is **refused**
//! and not swallowed: the agent is told that its answer was not used,
//! and why.
//!
//! # What the door **refuses**, on purpose
//!
//! - a **surface** that names a catalogue the door does not serve;
//! - **`metadata.extensions`** — a2ui's map for data craftkit does not
//!   know — because a payload the tree cannot interpret has nowhere to go;
//! - a **component** the layer does not know; and
//! - a **function** name that is in neither table.

